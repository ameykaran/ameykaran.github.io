"""
Extract the hero name's letter outlines from the Bucklane font as SVG paths.

    python3 scripts/name_glyphs.py [path/to/bucklane.ttf]

Writes src/data/nameGlyphs.ts, used by src/components/DrawnName.tsx to draw
the name as if with a pen, starting from the apex of the "A".

- Coordinates are font units (1000 per em), y pointing down, baseline at 0,
  so 1000 units == 1em of the old <h1> text.
- The A's outer contour is rotated to start at its apex (its highest point)
  and moved to the front, so the stroke animation begins at the tip.
- "Amey Karan" has no kerning or ligatures in this font, so letters sit at
  their plain advance widths (checked with Pillow/raqm when this was written).
"""

import json
import sys
from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "bucklane.ttf"
OUT = ROOT / "src" / "data" / "nameGlyphs.ts"
TEXT = "Amey Karan"


def contours(rec):
    cs, cur = [], []
    for op, args in rec.value:
        cur.append((op, args))
        if op in ("closePath", "endPath"):
            cs.append(cur)
            cur = []
    return cs


def to_svg(cs, dx):
    sp = SVGPathPen(None, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    tp = TransformPen(sp, (1, 0, 0, -1, dx, 0))  # flip y, shift to pen position
    for c in cs:
        for op, args in c:
            getattr(tp, op)(*args)
    return sp.getCommands()


def start_at_apex(cs):
    """Rotate the contour holding the highest point so it starts there; move it first."""
    best = None
    for ci, c in enumerate(cs):
        for k, (op, a) in enumerate(c):
            if a and (best is None or a[-1][1] > best[0][1]):
                best = (a[-1], ci, k)
    (ax, ay), ci, k = best
    c = cs[ci]
    if k > 0:
        start = c[0][1][0]
        body = c[1:-1]
        if body[-1][1][-1] != start:
            body = body + [("lineTo", (start,))]
        kb = k - 1
        rot = body[kb:] + body[:kb]  # rot[0] is the segment ending at the apex
        cs[ci] = [("moveTo", ((ax, ay),))] + rot[1:] + [rot[0], ("closePath", ())]
    cs.insert(0, cs.pop(ci))
    return cs


def main():
    f = TTFont(FONT)
    gs, cmap, hmtx = f.getGlyphSet(), f.getBestCmap(), f["hmtx"]
    x, glyphs, xs, ys = 0, [], [], []
    for ch in TEXT:
        gn = cmap[ord(ch)]
        if ch != " ":
            rec = RecordingPen()
            gs[gn].draw(rec)
            cs = contours(rec)
            if ch == "A":
                cs = start_at_apex(cs)
            ends = [a[-1] for c in cs for _, a in c if a]
            xs += [x + p[0] for p in ends]
            ys += [-p[1] for p in ends]
            glyphs.append({"ch": ch, "d": to_svg(cs, x)})
        x += hmtx[gn][0]
    pad = 40  # room for the pen stroke
    vb = [min(xs) - pad, -900, max(xs) - min(xs) + 2 * pad, 1200]  # 1.2em tall, baseline at 0
    OUT.write_text(
        "// Generated by scripts/name_glyphs.py from the Bucklane font. Do not edit.\n"
        f"export const NAME_VIEWBOX = {json.dumps(vb)};\n"
        f"export const NAME_GLYPHS: {{ ch: string; d: string }}[] = {json.dumps(glyphs, ensure_ascii=False)};\n"
    )
    print("wrote", OUT, f"({OUT.stat().st_size} bytes)", "viewBox", vb)


if __name__ == "__main__":
    main()
